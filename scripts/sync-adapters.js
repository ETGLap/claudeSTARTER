#!/usr/bin/env node
"use strict";

// Starter maintenance tool. Runtime hooks and host projects do not depend on this script.
const fs = require("node:fs");
const path = require("node:path");
const ROOT = path.resolve(__dirname, "..");
const read = (file) => fs.readFileSync(path.join(ROOT, file), "utf8");
const generated = "Generated by scripts/sync-adapters.js; edit the canonical .claude source.";

function walk(dir) {
  return fs.readdirSync(path.join(ROOT, dir), { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name)).flatMap((entry) =>
    entry.isDirectory() ? (entry.name === "fixtures" ? [] : walk(`${dir}/${entry.name}`)) : [`${dir}/${entry.name}`]);
}

function platformText(text) {
  return text.replaceAll("`CLAUDE.md`", "`AGENTS.md`")
    .replaceAll(".claude/templates/claude-root.md", ".claude/templates/agents-root.md")
    .replace("keeping\n  `@.claude/CLAUDE.md` as the first line.", "preserving the template's explicit shared-core reference.")
    .replaceAll("`.claude/skills/<stack>/SKILL.md`", "`.agents/skills/<stack>/SKILL.md`")
    .replace("Check `.claude/rules/`: the shipped rules are path-scoped and activate on their own, but\n  adjust a glob if this project's layout would miss it.", "Read the applicable `.claude/rules/` explicitly; Codex does not automatically load Claude path rules.");
}

function generatedFiles() {
  const files = new Map();
  for (const source of walk(".claude/hooks").filter((file) => path.dirname(file) === ".claude/hooks" && file.endsWith(".js") && !file.endsWith(".test.js"))) {
    files.set(source.replace(".claude/", ".codex/"), `// ${generated}\n"use strict";\nrequire("../../.claude/hooks/lib/codex.js").runCodexHook(${JSON.stringify(path.basename(source))});\n`);
  }
  for (const source of walk(".claude/skills").filter((file) => file.endsWith("/SKILL.md"))) {
    const text = platformText(read(source));
    const end = text.indexOf("\n---", 3) + 4;
    files.set(source.replace(".claude/", ".agents/"), text.slice(0, end) + `\n\n<!-- ${generated} -->` + text.slice(end));
  }
  for (const source of [...walk(".claude/agents"), ...walk(".claude/templates/agents")].filter((file) => file.endsWith(".md"))) {
    const text = read(source);
    const name = text.match(/^name: (.+)$/m)[1];
    const description = text.match(/^description: (.+)$/m)[1];
    const body = text.slice(text.indexOf("\n---", 3) + 4).trim();
    const skills = [...text.slice(0, text.indexOf("\n---", 3)).matchAll(/^  - (.+)$/gm)].map((m) => m[1]);
    const preface = "Read .claude/CLAUDE.md and applicable project AGENTS.md constraints. Remain read-only.\n" +
      skills.map((name) => `Read .claude/skills/${name}/SKILL.md when that lens applies.\n`).join("");
    files.set(`.codex/${source.includes("/templates/") ? "agents.optional" : "agents"}/${name}.toml`, `# ${generated}\nname = ${JSON.stringify(name)}\ndescription = ${JSON.stringify(description)}\nsandbox_mode = "read-only"\ndeveloper_instructions = ${JSON.stringify(platformText(preface + body))}\n`);
  }
  for (const [source, target] of [[".claude/settings.json", ".codex/hooks.json"], [".claude/templates/hooks.optional.json", ".codex/hooks.optional.json"]]) {
    const settings = JSON.parse(read(source));
    const hooks = JSON.parse(JSON.stringify(settings.hooks));
    delete hooks.Notification; // No matching Codex event in the documented contract.
    for (const groups of Object.values(hooks)) for (const group of groups) {
      if (group.matcher?.includes("Write")) group.matcher = `apply_patch|${group.matcher}`;
      for (const hook of group.hooks) {
        const name = hook.command.match(/\.claude\/hooks\/([\w-]+\.js)/)[1];
        const suffix = hook.command.endsWith(' stop') ? ' stop' : '';
        hook.command = 'node "$(git rev-parse --show-toplevel)/.codex/hooks/' + name + '"' + suffix;
      }
    }
    files.set(target, JSON.stringify({ description: generated + " Requires a trusted Git project and Node on PATH.", hooks }, null, 2) + "\n");
  }
  files.set(".codex/hooks/README.md", `# Codex hook adapters\n\n${generated}\n\nImplementation and configuration live in [.claude/hooks](../../.claude/hooks/README.md).\nInstall .claude with these adapters. Hook commands resolve through the Git root.\nCodex does not support an ask decision; the adapter returns deny with an explanation.\nSee the [platform guide](../../.claude/README.md#codex) for coverage and limitations.\n`);
  files.set("AGENTS.md", `<!-- ${generated} Starter repository only; do not copy this project layer into host projects. -->\n\n` +
    platformText(read("CLAUDE.md").replace(/^@.*\n/gm, "")) + "\n" + platformText(read(".claude/CLAUDE.md")));
  return files;
}

function isGenerated(text) {
  if (text.startsWith(`// ${generated}\n`) || text.startsWith(`# ${generated}\n`)) return true;
  const end = text.startsWith('---\n') ? text.indexOf('\n---\n', 4) : -1;
  return end !== -1 && text.slice(end + 5).startsWith(`\n<!-- ${generated} -->\n`);
}

// Prune only marked generator-owned files; preserve custom adapters.
function staleGeneratedFiles(expected = generatedFiles()) {
  return [".codex/hooks", ".codex/agents", ".codex/agents.optional", ".agents/skills"]
    .filter((dir) => fs.existsSync(path.join(ROOT, dir)))
    .flatMap(walk).filter((file) => !expected.has(file) && isGenerated(read(file)));
}

function sync(check = false) {
  const changed = [];
  const expected = generatedFiles();
  for (const [file, content] of expected) {
    if (fs.existsSync(path.join(ROOT, file)) && read(file) === content) continue;
    changed.push(file);
    if (!check) { fs.mkdirSync(path.dirname(path.join(ROOT, file)), { recursive: true }); fs.writeFileSync(path.join(ROOT, file), content); }
  }
  for (const file of staleGeneratedFiles(expected)) {
    changed.push(file);
    if (!check) fs.unlinkSync(path.join(ROOT, file));
  }
  return changed;
}

if (require.main === module) {
  const check = process.argv.includes("--check");
  const changed = sync(check);
  if (check && changed.length) { console.error(`Stale adapters:\n${changed.join("\n")}`); process.exitCode = 1; }
  else console.log(check ? "Adapters match canonical sources." : `Updated ${changed.length} adapters.`);
}

module.exports = { generatedFiles, staleGeneratedFiles, sync, platformText, isGenerated };
